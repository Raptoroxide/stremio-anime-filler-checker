// AnimeFillerList provider (primary data source).
//
// Runtime behaviour:
//  - The shows index is normally served from the bundled seed (titles+slugs
//    only) so most lookups need zero upstream calls; a live refresh of the
//    index happens at most once per 24h per warm instance and only when a
//    lookup genuinely needs it.
//  - A show page is fetched only on a real episode lookup, parsed, and cached
//    for 24h. robots.txt (Crawl-delay: 10) is honoured by the HTTP layer.
//  - On upstream failure, previously cached (stale) show data is served and
//    flagged; if nothing is cached the provider reports an error so the
//    FillerLists fallback can take over.
//  - After fetching a show page its H1 title is cross-checked against the
//    matched index entry, guarding against the site's occasional slug/title
//    mismatches in its index.
//
// Only public episode classification data (episode number, type label,
// episode title) is parsed. Nothing is republished or bundled except the
// title→slug routing seed, and every result stores the canonical source URL.

import { findShowMatch } from '../matching/match.js'
import { mapToAbsolute } from '../matching/episodes.js'
import { normalizeTitle } from '../matching/normalize.js'
import { normalizeVerdictKey } from '../shared/types.js'
import { dedupe } from '../cache/memory.js'

export const AFL_BASE = 'https://www.animefillerlist.com'
const INDEX_URL = `${AFL_BASE}/shows`
const INDEX_TTL = 24 * 60 * 60 * 1000
const INDEX_ERROR_TTL = 30 * 60 * 1000
const SHOW_TTL = 24 * 60 * 60 * 1000
const SHOW_ERROR_TTL = 15 * 60 * 1000
const MAX_EPISODES = 3000

const AFL_TYPE_CLASSES = new Set(['manga_canon', 'mixed_canon/filler', 'filler', 'anime_canon'])

// The seed is generated by `npm run update-data`; tolerate its absence so the
// very first generation can run.
let AFL_SEED = { retrievedAt: null, url: INDEX_URL, shows: [] }
try {
  const mod = await import('./data/afl-shows-seed.js')
  if (mod && Array.isArray(mod.AFL_SEED.shows)) AFL_SEED = mod.AFL_SEED
} catch { /* seed not generated yet */ }

function decodeEntities (text) {
  return String(text)
    .replace(/&#(\d+);/g, (_, code) => {
      try { return String.fromCodePoint(Number(code)) } catch { return '' }
    })
    .replace(/&amp;/g, '&')
    .replace(/&apos;/g, "'")
    .replace(/&#0?39;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
}

/** Parse the public /shows index into [{slug, title}]. */
export function parseShowIndex (html) {
  const out = []
  const seen = new Set()
  const re = /<a\s+href="\/shows\/([a-z0-9-]+)"[^>]*>([^<]{1,160})<\/a>/g
  let m
  while ((m = re.exec(html)) !== null) {
    const slug = m[1]
    const title = decodeEntities(m[2]).replace(/\s+/g, ' ').trim()
    if (!title || seen.has(slug)) continue
    seen.add(slug)
    out.push({ slug, title })
  }
  return out
}

/** Parse "1-6, 8, 10-13" (tags stripped) into an episode number list. */
export function parseEpisodeRanges (text) {
  const eps = []
  for (const part of String(text || '').split(',')) {
    const t = part.trim()
    if (!t) continue
    const rm = t.match(/^(\d{1,4})(?:\s*-\s*(\d{1,4}))?$/)
    if (!rm) continue
    const a = Number(rm[1])
    const b = rm[2] != null ? Number(rm[2]) : a
    if (a < 1 || b < a || b - a > 2000) continue
    for (let i = a; i <= b; i++) eps.push(i)
  }
  return eps
}

/**
 * Parse a show page. Prefers the structured episode table; falls back to the
 * grouped "Quick List" ranges. Throws when neither yields episodes.
 * @returns {{episodes: Map<number,{type:string,title:string}>, showTitle: string, minEpisode: number, maxEpisode: number}}
 */
export function parseShowPage (html) {
  const episodes = new Map()

  const rowRe = /<tr[^>]*\sclass="([^"]*)"[^>]*>([\s\S]*?)<\/tr>/g
  let m
  while ((m = rowRe.exec(html)) !== null) {
    const cls = (m[1].trim().split(/\s+/)[0] || '')
    if (!AFL_TYPE_CLASSES.has(cls)) continue
    const row = m[2]
    const num = row.match(/<td[^>]*class="Number"[^>]*>\s*(\d{1,4})\s*<\/td>/)
    if (!num) continue
    const number = Number(num[1])
    if (number < 1 || number > MAX_EPISODES) continue
    const titleMatch = row.match(/<td[^>]*class="Title"[^>]*>([\s\S]*?)<\/td>/)
    const title = titleMatch ? decodeEntities(titleMatch[1].replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').trim() : ''
    episodes.set(number, { type: normalizeVerdictKey(cls), title })
  }

  if (episodes.size === 0) {
    const groupRe = /<div\s+class="(manga_canon|mixed_canon\/filler|filler|anime_canon)"[^>]*>[\s\S]{0,600}?<span\s+class="Episodes"[^>]*>([\s\S]*?)<\/span>/g
    while ((m = groupRe.exec(html)) !== null) {
      const type = normalizeVerdictKey(m[1])
      const inner = m[2].replace(/<[^>]+>/g, ' ')
      for (const ep of parseEpisodeRanges(inner)) {
        if (!episodes.has(ep)) episodes.set(ep, { type, title: '' })
      }
    }
  }

  if (episodes.size === 0) throw new Error('afl: no episode data found on page')
  if (episodes.size > MAX_EPISODES) throw new Error('afl: implausible episode count')

  let min = Infinity
  let max = 0
  for (const n of episodes.keys()) {
    if (n < min) min = n
    if (n > max) max = n
  }

  let showTitle = ''
  const h1 = html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/)
  if (h1) {
    showTitle = decodeEntities(h1[1].replace(/<[^>]+>/g, '')).replace(/\s+/g, ' ').trim()
    showTitle = showTitle.replace(/\s*Filler List\s*$/i, '').trim()
  }

  return { episodes, showTitle, minEpisode: min === Infinity ? 1 : min, maxEpisode: max }
}

export function createAnimeFillerListProvider ({ http, now, cache, inflight = new Map(), seed = AFL_SEED }) {
  const seedValue = { shows: Array.isArray(seed.shows) ? seed.shows : [], source: 'seed', retrievedAt: seed.retrievedAt }

  async function getIndex (scope, { allowFetch }) {
    const hit = cache.peek('afl:index', now())
    if (hit.state === 'fresh') return hit.value
    if (!allowFetch) return seedValue
    return dedupe(inflight, 'afl:index', async () => {
      try {
        const res = await http.fetchText(INDEX_URL, { scope, headers: { Accept: 'text/html,application/xhtml+xml' } })
        const shows = parseShowIndex(res.text)
        if (shows.length < 50) throw new Error('afl: show index parse yielded too few shows')
        const value = { shows, source: 'live', retrievedAt: new Date(now()).toISOString() }
        cache.set('afl:index', value, INDEX_TTL, now())
        return value
      } catch (err) {
        if (hit.state === 'stale' && hit.value && Array.isArray(hit.value.shows)) {
          return { ...hit.value, stale: true }
        }
        // Negative-cache the failure briefly, and fall back to the seed.
        const fallback = { ...seedValue, stale: true }
        cache.set('afl:index', fallback, INDEX_ERROR_TTL, now())
        return fallback
      }
    })
  }

  async function getShowPage (slug, scope) {
    const key = `afl:show:${slug}`
    const hit = cache.peek(key, now())
    if (hit.state === 'fresh') return hit.value
    return dedupe(inflight, key, async () => {
      try {
        const res = await http.fetchText(`${AFL_BASE}/shows/${slug}`, { scope, headers: { Accept: 'text/html,application/xhtml+xml' } })
        const parsed = parseShowPage(res.text)
        const value = {
          ...parsed,
          slug,
          sourceUrl: `${AFL_BASE}/shows/${slug}`,
          checkedAt: new Date(now()).toISOString(),
          fromCache: false
        }
        cache.set(key, value, SHOW_TTL, now())
        return value
      } catch (err) {
        if (hit.state === 'stale') return { ...hit.value, fromCache: true, stale: true }
        cache.set(key, null, SHOW_ERROR_TTL, now())
        throw err
      }
    })
  }

  function unknownRecord (args, page, match, reason, absolute) {
    return {
      verdict: 'unknown',
      reason,
      seriesTitle: args.title,
      matchedAlias: match && match.title !== args.title ? match.title : undefined,
      showTitle: (page && page.showTitle) || (match && match.title) || '',
      episodeNumber: Number.isInteger(absolute) ? absolute : null,
      episodeTitle: undefined,
      seasonPage: false,
      mappingConfidence: 'medium',
      sourceName: 'AnimeFillerList',
      sourceUrl: page ? page.sourceUrl : `${AFL_BASE}/shows/${match ? match.entry.slug : ''}`,
      checkedAt: page ? page.checkedAt : new Date(now()).toISOString(),
      fromCache: !!(page && page.fromCache)
    }
  }

  /**
   * @param {{title:string, aliases?:string[], year?:number|null, season:number, episode:number,
   *          seasonCounts?:Map<number,number>|null, imdbId?:string|null}} args
   */
  async function lookup (args, scope, { allowFetch = true } = {}) {
    try {
      // Seed first: a bundled-seed match needs no index fetch at all, which
      // keeps the common path to a single upstream request (the show page).
      let match = findShowMatch(seedValue.shows, {
        title: args.title,
        aliases: args.aliases,
        year: args.year,
        season: args.season
      })
      if (!match && allowFetch) {
        const index = await getIndex(scope, { allowFetch: true })
        if (index && Array.isArray(index.shows) && index.shows.length > 0) {
          match = findShowMatch(index.shows, {
            title: args.title,
            aliases: args.aliases,
            year: args.year,
            season: args.season
          })
        }
      }
      if (!match) return { status: 'no-match' }

      let page
      try {
        page = await getShowPage(match.entry.slug, scope)
      } catch (err) {
        return { status: 'error', reason: 'show page unavailable' }
      }
      if (page == null) return { status: 'error', reason: 'show page unavailable' }

      // Cross-check the page's own title against the index entry to guard
      // against slug/title mismatches in the site's index.
      if (page.showTitle) {
        const pageNorm = normalizeTitle(page.showTitle)
        const wantNorm = normalizeTitle(match.title)
        if (pageNorm && wantNorm && pageNorm !== wantNorm && !pageNorm.includes(wantNorm) && !wantNorm.includes(pageNorm)) {
          return { status: 'no-match', reason: 'slug/title mismatch on source page' }
        }
      }

      const seasonPage = match.method === 'season-page'
      const mapping = mapToAbsolute({
        season: args.season,
        episode: args.episode,
        seasonCounts: args.seasonCounts,
        sourceTotal: page.maxEpisode,
        seasonPage,
        pageMinEpisode: page.minEpisode
      })

      if (mapping.error) {
        return { status: 'ok', record: unknownRecord(args, page, match, mapping.error, mapping.absolute) }
      }

      const ep = page.episodes.get(mapping.absolute)
      if (!ep) {
        return { status: 'ok', record: unknownRecord(args, page, match, 'not-listed', mapping.absolute) }
      }

      return {
        status: 'ok',
        record: {
          verdict: ep.type,
          reason: undefined,
          seriesTitle: args.title,
          matchedAlias: match.title !== args.title ? match.title : undefined,
          showTitle: page.showTitle || match.title,
          episodeNumber: mapping.absolute,
          episodeTitle: ep.title || undefined,
          seasonPage,
          mappingConfidence: mapping.confidence,
          sourceName: 'AnimeFillerList',
          sourceUrl: page.sourceUrl,
          sourceUpdatedAt: undefined,
          checkedAt: page.checkedAt,
          fromCache: !!page.fromCache
        }
      }
    } catch (err) {
      return { status: 'error', reason: (err && err.message) || 'unexpected provider error' }
    }
  }

  return { name: 'AnimeFillerList', lookup, getIndex, getShowPage, seed: seedValue }
}
